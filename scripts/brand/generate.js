// Generates every brand asset from design.js into the project.
// Usage: npm i --no-save sharp && node scripts/brand/generate.js
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const d = require('./design');

const ROOT = path.resolve(__dirname, '../..');
const RES = path.join(ROOT, 'android/app/src/main/res');
const BRAND_DIR = path.join(ROOT, 'docs/brand');

const hex = c => `#FF${c.slice(1).toUpperCase()}`;
const write = (p, s) => {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, s);
};

// ---------------------------------------------------------------- Android vector drawables
const VEC_HEAD = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand/generate.js. Edit scripts/brand/design.js, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">`;

const gradientFill = (from, to, x0, y0, x1, y1) => `
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="${x0}" android:startY="${y0}" android:endX="${x1}" android:endY="${y1}">
                    <item android:offset="0" android:color="${hex(from)}" />
                    <item android:offset="1" android:color="${hex(to)}" />
                </gradient>
            </aapt:attr>`;

const highlight = `
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="27" android:centerY="16" android:gradientRadius="81">
                    <item android:offset="0" android:color="#38FFFFFF" />
                    <item android:offset="1" android:color="#00FFFFFF" />
                </gradient>
            </aapt:attr>`;

const stroke = (pathData, color, width) => `
        <path android:pathData="${pathData}" android:strokeColor="${color}" android:strokeWidth="${width}"
            android:strokeLineCap="round" android:fillColor="#00000000" />`;

const glyph = (color, accent) =>
  d.STROKES.map(p => stroke(p, color, d.STROKE)).join('') + stroke(d.SLASH, accent, d.SLASH_WIDTH);

const vector = body => `${VEC_HEAD}${body}
</vector>
`;

const background = vector(`
        <path android:pathData="M0,0h108v108h-108z">${gradientFill(d.BRAND.from, d.BRAND.to, 0, 0, 108, 108)}
        </path>
        <path android:pathData="M0,0h108v108h-108z">${highlight}
        </path>`);

const foreground = vector(glyph('#FFFFFFFF', hex(d.BRAND.accent)));

// Android 13+ themed icons: single colour, the system tints it.
const monochrome = vector(glyph('#FF000000', '#FF000000'));

// Splash: brand squircle with the mark, sized to sit inside the splash's circular mask.
const S = 0.46;
const side = +(108 * S).toFixed(2);
const off = +((108 - side) / 2).toFixed(2);
const r = (k) => +(k * side).toFixed(2);
const squirclePath = `M${r(0.28)},0 H${r(0.72)} C${r(0.9)},0 ${side},${r(0.1)} ${side},${r(0.28)} V${r(
  0.72,
)} C${side},${r(0.9)} ${r(0.9)},${side} ${r(0.72)},${side} H${r(0.28)} C${r(0.1)},${side} 0,${r(0.9)} 0,${r(
  0.72,
)} V${r(0.28)} C0,${r(0.1)} ${r(0.1)},0 ${r(0.28)},0 Z`;
const splash = vector(`
    <group android:translateX="${off}" android:translateY="${off}">
        <path android:pathData="${squirclePath}">${gradientFill(d.BRAND.from, d.BRAND.to, 0, 0, side, side)}
        </path>
        <group android:scaleX="${S}" android:scaleY="${S}">${glyph('#FFFFFFFF', hex(d.BRAND.accent))}
        </group>
    </group>`);

write(path.join(RES, 'drawable/ic_launcher_background.xml'), background);
write(path.join(RES, 'drawable/ic_launcher_foreground.xml'), foreground);
write(path.join(RES, 'drawable/ic_launcher_monochrome.xml'), monochrome);
write(path.join(RES, 'drawable/splash_icon.xml'), splash);

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
write(path.join(RES, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
write(path.join(RES, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);

// ---------------------------------------------------------------- PNGs
async function png(svg, size, out) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  await sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toFile(out);
}

(async () => {
  // Legacy launcher icons (Android 7.x has no adaptive icons).
  const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [dpi, size] of Object.entries(densities)) {
    await png(d.legacyIconSvg(size, false), size, path.join(RES, `mipmap-${dpi}/ic_launcher.png`));
    await png(d.legacyIconSvg(size, true), size, path.join(RES, `mipmap-${dpi}/ic_launcher_round.png`));
  }
  // Play Store listing icon: 512x512, full square (Play applies its own mask).
  await png(d.iconSvg(512, 'square'), 512, path.join(BRAND_DIR, 'play-store-icon-512.png'));
  await png(d.iconSvg(1024, 'squircle'), 1024, path.join(BRAND_DIR, 'brand-mark-1024.png'));
  write(path.join(BRAND_DIR, 'brand-mark.svg'), d.iconSvg(1024, 'squircle'));
  write(path.join(BRAND_DIR, 'brand-mark-square.svg'), d.iconSvg(1024, 'square'));
  console.log('ok');
})();
